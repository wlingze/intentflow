// schemaPath 是唯一数据契约。生成物与它不一致，说明有人手改了 types.gen.go，
// 或者改了 schema 却忘了跑 make schema。
const schemaPath = "../../schema/openapi.yaml"

type enumBlock struct {
	line   int
	values []string
}

// parseEnums 从 OpenAPI YAML 文本里取出所有 enum 取值。
// 只处理本项目实际用到的两种写法：行内 `enum: [a, b]`，以及
// `enum:` 后面跟多行 `- a` 列表。不引入 YAML 依赖。
func parseEnums(src string) []enumBlock {
	lines := strings.Split(src, "\n")
	var blocks []enumBlock
	for i := 0; i < len(lines); i++ {
		at := strings.Index(lines[i], "enum:")
		if at < 0 {
			continue
		}
		block := enumBlock{line: i + 1}
		rest := strings.TrimSpace(lines[i][at+len("enum:"):])
		if open := strings.Index(rest, "["); open >= 0 {
			inner := rest[open+1:]
			if close := strings.Index(inner, "]"); close >= 0 {
				inner = inner[:close]
			}
			for _, value := range strings.Split(inner, ",") {
				if value = cleanEnumValue(value); value != "" {
					block.values = append(block.values, value)
				}
			}
			blocks = append(blocks, block)
			continue
		}
		// 块状写法：后续每行以 "- " 开头。
		for j := i + 1; j < len(lines); j++ {
			item := strings.TrimSpace(lines[j])
			if !strings.HasPrefix(item, "- ") {
				break
			}
			if value := cleanEnumValue(strings.TrimPrefix(item, "- ")); value != "" {
				block.values = append(block.values, value)
			}
			i = j
		}
		blocks = append(blocks, block)
	}
	return blocks
}

func cleanEnumValue(raw string) string {
	value := strings.TrimSpace(raw)
	value = strings.Trim(value, `"'`)
	return strings.TrimSpace(value)
}

func readText(t *testing.T, path string) string {
	t.Helper()
	buf, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(buf)
}

// TestGeneratedTypesCarryEverySchemaEnum 保证每个 enum 取值都出现在生成代码里。
// 有人在 types.gen.go 里手改常量、或改了 schema 没重新生成，这里就会失败。
func TestGeneratedTypesCarryEverySchemaEnum(t *testing.T) {
	schema := readText(t, schemaPath)
	gen := readText(t, "types.gen.go")

	blocks := parseEnums(schema)
	if len(blocks) < 10 {
		t.Fatalf("parsed %d enum blocks from %s, expected the parser to find the schema enums", len(blocks), schemaPath)
	}

	seen := 0
	for _, block := range blocks {
		if len(block.values) == 0 {
			t.Errorf("%s:%d has an enum with no parsed values", schemaPath, block.line)
			continue
		}
		for _, value := range block.values {
			seen++
			// 生成物里的常量形如 Name Type = "value"。只认这种赋值形式：
			// 结构体的 json:"value" 标签也会命中裸的 "value"，不能当证据。
			if !strings.Contains(gen, `= "`+value+`"`) {
				t.Errorf("%s:%d enum value %q does not appear in types.gen.go; run make schema",
					schemaPath, block.line, value)
			}
		}
	}
	if seen < 20 {
		t.Fatalf("checked only %d enum values, expected the whole schema", seen)
	}
}

// TestGeneratedTypesAreNotHandWritten 确认文件头仍是生成器标记。
func TestGeneratedTypesAreNotHandWritten(t *testing.T) {
	gen := readText(t, "types.gen.go")
	for _, want := range []string{"Code generated by", "oapi-codegen", "DO NOT EDIT"} {
		if !strings.Contains(gen, want) {
			t.Fatalf("types.gen.go lost the %q marker; it must stay generated output", want)
		}
	}
}

// 基线状态四个字段必须进入 JSON 契约，前端靠它们显示落后提示。
func TestReviewBaseStatusSerializes(t *testing.T) {
	want := Review{
		BaseLabel:    "merge-base(origin/main@abc12345)",
		BaseBehind:   3,
		BaseUpstream: "origin/main",
		NeedsRebase:  true,
	}
	buf, err := json.Marshal(want)
	if err != nil {
		t.Fatal(err)
	}
	var raw map[string]any
	if err := json.Unmarshal(buf, &raw); err != nil {
		t.Fatal(err)
	}
	for key, value := range map[string]any{
		"baseLabel":    want.BaseLabel,
		"baseBehind":   float64(want.BaseBehind),
		"baseUpstream": want.BaseUpstream,
		"needsRebase":  want.NeedsRebase,
	} {
		if raw[key] != value {
			t.Errorf("%s = %v, want %v", key, raw[key], value)
		}
	}
	var round Review
	if err := json.Unmarshal(buf, &round); err != nil {
		t.Fatal(err)
	}
	if round.BaseLabel != want.BaseLabel || round.BaseBehind != want.BaseBehind ||
		round.BaseUpstream != want.BaseUpstream || round.NeedsRebase != want.NeedsRebase {
		t.Fatalf("round trip = %+v", round)
	}
}
